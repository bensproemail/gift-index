#!/usr/bin/env node
// Generates CODEMAP.md: every source file with its exported names and first doc line.
// Usage: node scripts/codemap.mjs [rootDir=src]
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const root = process.argv[2] || (existsSync('src') ? 'src' : '.');
const EXTS = new Set(['.js', '.jsx', '.ts', '.tsx', '.mjs', '.cjs', '.vue', '.svelte', '.py']);
const SKIP = new Set(['node_modules', '.git', 'dist', 'build', '.next', 'coverage', '.claude', '.venv', '__pycache__']);

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    if (SKIP.has(name) || name.startsWith('.')) continue;
    const p = join(dir, name);
    const s = statSync(p);
    if (s.isDirectory()) walk(p, out);
    else if (EXTS.has(extname(name)) && !/\.(test|spec)\./.test(name)) out.push(p);
  }
  return out;
}

const exportRe = /export\s+(?:default\s+)?(?:async\s+)?(?:function\*?|const|let|class|type|interface|enum)\s+([A-Za-z0-9_$]+)/g;
const pyRe = /^(?:def|class)\s+([A-Za-z_][A-Za-z0-9_]*)/gm;

function describe(file) {
  const src = readFileSync(file, 'utf8');
  const names = new Set();
  const re = extname(file) === '.py' ? pyRe : exportRe;
  for (const m of src.matchAll(re)) if (!m[1].startsWith('_')) names.add(m[1]);
  const doc = src.match(/^\s*(?:\/\/|#|\/\*\*?|\*)\s*(.+)$/m);
  const summary = doc ? doc[1].replace(/\*\/\s*$/, '').trim() : '';
  return { names: [...names], summary };
}

const files = walk(root);
const groups = new Map();
for (const f of files) {
  const rel = relative('.', f);
  const dir = rel.includes('/') ? rel.slice(0, rel.lastIndexOf('/')) : '.';
  if (!groups.has(dir)) groups.set(dir, []);
  groups.get(dir).push({ rel, ...describe(f) });
}

let md = `# Code map\n\nAuto-generated by \`npm run codemap\`. Do not edit by hand.\n${files.length} files.\n`;
for (const [dir, entries] of groups) {
  md += `\n## ${dir}/\n`;
  for (const e of entries) {
    const exp = e.names.length ? ` — exports: ${e.names.slice(0, 12).join(', ')}${e.names.length > 12 ? ', …' : ''}` : '';
    const sum = e.summary ? ` — ${e.summary.slice(0, 100)}` : '';
    md += `- \`${e.rel}\`${exp}${sum}\n`;
  }
}
writeFileSync('CODEMAP.md', md);
console.log(`CODEMAP.md written (${files.length} files)`);
